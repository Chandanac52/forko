"""Turn a finished build into setup commands for the user's operating system."""


def setup_commands(build: dict) -> list[dict]:
    o, n = build["repo"]["owner"], build["repo"]["name"]
    win = build["os"] == "windows"
    cmds = [("Clone the repository", f"git clone https://github.com/{o}/{n}.git"),
            ("Enter the project folder", f"cd {n}")]
    ver = build["runtime"].split()[-1]
    if build["stack"] == "python":
        applied = [f for f in build["fixes"] if f.get("worked") and f.get("unix")]
        for f in applied:
            if f.get("phase") != "after_venv":
                cmds.append((f"Apply fix: {f['what_changed']}", f["windows"] if win else f["unix"]))
        cmds.append((f"Create a virtual environment ({build['runtime']})",
                     f"py -{ver} -m venv .venv" if win else f"python{ver} -m venv .venv"))
        cmds.append(("Activate it", r".venv\Scripts\Activate.ps1" if win else "source .venv/bin/activate"))
        for f in applied:
            if f.get("phase") == "after_venv":
                cmds.append((f"Apply fix: {f['what_changed']}", f["windows"] if win else f["unix"]))
        for c in build["install_final"]:
            cmds.append(("Install dependencies", c))
        if build["tests_ran"]:
            cmds.append(("Run the tests", "python -m pytest -q"))
    else:
        for c in build["install_final"]:
            cmds.append((f"Install dependencies ({build['runtime']})", c))
        if build["build_ran"]:
            cmds.append(("Build the project", "npm run build"))
        if build["tests_ran"]:
            cmds.append(("Run the tests", '$env:CI="true"; npm test' if win else "CI=true npm test"))
    return [{"title": t, "command": c} for t, c in cmds]


def render_setup_file(build: dict) -> tuple[str, str]:
    win = build["os"] == "windows"
    head = (f"# Generated by Forko. Verified in a Linux container ({build.get('runtime', '')}).\n"
            f"# Commands for other operating systems are translated, not executed there.\n")
    lines = [c["command"] for c in build["setup_commands"]]
    if win:
        return "setup.ps1", head + "\n".join(lines) + "\n"
    return "setup.sh", "#!/usr/bin/env bash\nset -e\n" + head + "\n".join(lines) + "\n"
